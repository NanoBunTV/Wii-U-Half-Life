<#
.SYNOPSIS
  Assembles the gx2gl shaders (src/gx2gl/shaders/*.vsh + *.psh) into src/gx2gl/shaders/gx2gl_shaders.h.

.DESCRIPTION
  Needs latte-assembler.exe from decaf-emu in tools/latte-assembler/ (see Docs/BUILDING.md). The generated
  header is kept in the repository, so a normal build doesn't need the assembler; run this script after
  changing a shader.

  Each vertex/pixel shader pair <name>.vsh + <name>.psh becomes one GFD file, embedded as
  `static const unsigned char gx2gl_shader_<name>[]`.
#>
$ErrorActionPreference = 'Stop'

$root = Resolve-Path (Join-Path $PSScriptRoot '..')
$assembler = Join-Path $root 'tools\latte-assembler\latte-assembler.exe'
$shaderDir = Join-Path $root 'src\gx2gl\shaders'
$outHeader = Join-Path $shaderDir 'gx2gl_shaders.h'

if (-not (Test-Path -LiteralPath $assembler)) {
	throw "latte-assembler not found at $assembler (see Docs/BUILDING.md)"
}

$tmp = Join-Path ([System.IO.Path]::GetTempPath()) 'gx2gl-shaders'
New-Item -ItemType Directory -Force $tmp | Out-Null

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('// generated by scripts/build-shaders.ps1 from the .vsh/.psh files next to it, do not edit')
[void]$sb.AppendLine('#pragma once')
[void]$sb.AppendLine()

foreach ($vsh in Get-ChildItem -LiteralPath $shaderDir -Filter '*.vsh' | Sort-Object Name) {
	$name = $vsh.BaseName
	$psh = Join-Path $shaderDir "$name.psh"
	if (-not (Test-Path -LiteralPath $psh)) { throw "$name.vsh has no matching $name.psh" }

	$gsh = Join-Path $tmp "$name.gsh"
	Remove-Item -LiteralPath $gsh -ErrorAction SilentlyContinue
	& $assembler assemble "--vsh=$($vsh.FullName)" "--psh=$psh" $gsh
	if ($LASTEXITCODE -ne 0 -or -not (Test-Path -LiteralPath $gsh)) { throw "latte-assembler failed for $name" }

	$bytes = [System.IO.File]::ReadAllBytes($gsh)
	Write-Host ("{0}: {1} bytes" -f $name, $bytes.Length)

	# GFD files must stay 256-byte aligned for GX2 (the program data is used in place)
	[void]$sb.AppendLine("static const unsigned char gx2gl_shader_$name[] __attribute__(( aligned( 256 ))) =")
	[void]$sb.AppendLine('{')
	for ($i = 0; $i -lt $bytes.Length; $i += 16) {
		$line = ($bytes[$i..([Math]::Min($i + 15, $bytes.Length - 1))] | ForEach-Object { '0x{0:x2},' -f $_ }) -join ' '
		[void]$sb.AppendLine("`t$line")
	}
	[void]$sb.AppendLine('};')
	[void]$sb.AppendLine()
}

[System.IO.File]::WriteAllText($outHeader, $sb.ToString())
Write-Host "Written: $outHeader"
